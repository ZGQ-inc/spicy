fun t(format: String, vararg args: Any?): String = I18n.t(format, *args)

/** Returns localized weather condition text based on current language. */
fun localizedWeather(description: String, condition: String = ""): String = I18n.localizedWeather(description, condition)

/** Returns localized city name based on current language. */
fun localizedCity(cityName: String): String = I18n.localizedCity(cityName)
