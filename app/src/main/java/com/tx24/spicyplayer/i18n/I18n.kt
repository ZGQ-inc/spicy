/**
 * Universal, Compose-reactive internationalization (i18n) engine for Spicy Player.
 * Defaults / falls back to English ("en"), with full support for Simplified Chinese ("zh").
 * When setting is "system", automatically queries current device locale.
 */
object I18n {
    /** Stored language setting: "system", "en", "zh", etc. */
    var appLanguage by mutableStateOf("system")

    /**
     * Effective language code ("en", "zh", etc.) taking into account system detection.
     */
    val currentLanguage: String
        get() {
            if (appLanguage != "system") return appLanguage
            val sysLang = Locale.getDefault().language.lowercase()
            return if (sysLang.startsWith("zh")) "zh" else "en"
        }

    fun isChinese(): Boolean = currentLanguage == "zh"

    /**
     * Translates English text to active language. If not found or language is English,
     * returns the English text fallback.
     */
    fun t(englishText: String): String {
        val lang = currentLanguage
        if (lang == "en") return englishText
        val table = translations[lang] ?: return englishText
        return table[englishText] ?: englishText
    }

    /**
     * Format version of [t] supporting varargs.
     */
    fun t(format: String, vararg args: Any?): String {
        val translatedFormat = t(format)
        return try {
            String.format(translatedFormat, *args)
        } catch (_: Exception) {
            translatedFormat
        }
    }

