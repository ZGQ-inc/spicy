    fun localizedWeather(description: String, condition: String): String {
        val raw = description.ifBlank { condition }
        if (raw.isBlank()) return ""
        return if (!isChinese()) {
            zhToEnWeather[raw] ?: raw
        } else {
            enToZhWeather[raw.lowercase()] ?: raw
        }
    }

    fun localizedCity(cityName: String): String {
        if (cityName.isBlank()) return ""
        return if (!isChinese()) {
            zhToEnCity[cityName] ?: cityName
        } else {
            enToZhCity[cityName.lowercase()] ?: cityName
        }
    }

    private val translations: Map<String, Map<String, String>> = mapOf(
        "zh" to zh,
    )
